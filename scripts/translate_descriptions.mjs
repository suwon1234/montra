async function update() {
  const ids = Object.keys(translations);
  console.log(`Updating ${ids.length} descriptions to Korean...`);
  let ok = 0, fail = 0;

  for (const id of ids) {
    const res = await fetch(`${SUPABASE_URL}/rest/v1/trends?id=eq.${id}`, {
      method: 'PATCH',
      headers: {
        'apikey': SUPABASE_KEY,
        'Authorization': `Bearer ${SUPABASE_KEY}`,
        'Content-Type': 'application/json',
        'Prefer': 'return=minimal',
      },
      body: JSON.stringify({ description: translations[id] }),
    });
    if (res.ok) { ok++; }
    else { fail++; const e = await res.text(); console.log(`FAIL ${id}: ${e.slice(0,100)}`); }
  }
  console.log(`\nDone: ${ok} updated, ${fail} failed`);
}

update();
